-- Additive schema. Existing tables and records are preserved.
CREATE TABLE IF NOT EXISTS mt_products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 price_cents BIGINT NOT NULL, stock INT NOT NULL DEFAULT 0,
 min_stock INT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, client_id BIGINT UNSIGNED NULL,
 appointment_id BIGINT UNSIGNED NULL UNIQUE, status VARCHAR(20) NOT NULL DEFAULT 'open',
 discount_cents BIGINT NOT NULL DEFAULT 0, notes VARCHAR(500) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL, closed_at DATETIME NULL, cancelled_at DATETIME NULL,
 created_by BIGINT UNSIGNED NOT NULL, INDEX mt_orders_status (status,created_at), FOREIGN KEY (client_id) REFERENCES mt_clients(id), FOREIGN KEY (appointment_id) REFERENCES mt_appointments(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 kind VARCHAR(12) NOT NULL, reference_id BIGINT UNSIGNED NOT NULL, description VARCHAR(120) NOT NULL,
 quantity INT NOT NULL, unit_cents BIGINT NOT NULL, barber_id INT UNSIGNED NULL,
 commission_bps INT NOT NULL DEFAULT 0, INDEX mt_items_order (order_id),
 FOREIGN KEY (order_id) REFERENCES mt_orders(id), FOREIGN KEY (barber_id) REFERENCES mt_barbers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_cash_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, opened_at DATETIME NOT NULL,
 closed_at DATETIME NULL, opening_cents BIGINT NOT NULL, counted_cents BIGINT NULL,
 expected_cents BIGINT NULL, opened_by BIGINT UNSIGNED NOT NULL, closed_by BIGINT UNSIGNED NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_ledger (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cash_id BIGINT UNSIGNED NOT NULL,
 order_id BIGINT UNSIGNED NULL, amount_cents BIGINT NOT NULL, method VARCHAR(20) NOT NULL,
 category VARCHAR(30) NOT NULL, description VARCHAR(200) NOT NULL, created_at DATETIME NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL, request_key VARCHAR(64) NOT NULL UNIQUE,
 reversal_of BIGINT UNSIGNED NULL UNIQUE, INDEX mt_ledger_date (created_at),
 INDEX mt_ledger_order (order_id), FOREIGN KEY (cash_id) REFERENCES mt_cash_sessions(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_commissions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 item_id BIGINT UNSIGNED NOT NULL UNIQUE, barber_id INT UNSIGNED NOT NULL,
 amount_cents BIGINT NOT NULL, created_at DATETIME NOT NULL, paid_ledger_id BIGINT UNSIGNED NULL,
 voided_at DATETIME NULL, INDEX mt_commission_barber (barber_id), FOREIGN KEY (barber_id) REFERENCES mt_barbers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_stock_moves (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL,
 delta INT NOT NULL, reason VARCHAR(200) NOT NULL, order_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL, created_by BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mt_business_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL,
 event VARCHAR(50) NOT NULL, entity_id BIGINT UNSIGNED NULL, created_at DATETIME NOT NULL,
 detail VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
